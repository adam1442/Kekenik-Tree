// Generates THIRD_PARTY_NOTICES.md from the production dependency tree (run: npm run licenses).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'));
const rootPkg = readJson(path.join(root, 'package.json'));

const COMPATIBLE = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'OFL-1.1', 'CC0-1.0', 'Unlicense']);

/** Resolves a package directory the way Node does, starting from `fromDir`. */
function resolvePackageDir(name, fromDir) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (existsSync(path.join(candidate, 'package.json'))) return candidate;
    if (dir === path.dirname(dir)) return null;
  }
}

const seen = new Map();
function visit(name, fromDir) {
  const dir = resolvePackageDir(name, fromDir);
  if (!dir || seen.has(dir)) return;
  const pkg = readJson(path.join(dir, 'package.json'));
  const licenseFile = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'LICENCE'].map((f) => path.join(dir, f)).find(existsSync);
  const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'UNKNOWN');
  seen.set(dir, { name: pkg.name, version: pkg.version, license, homepage: pkg.homepage ?? pkg.repository?.url ?? '', text: licenseFile ? readFileSync(licenseFile, 'utf8').trim() : '' });
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir);
}
for (const dep of Object.keys(rootPkg.dependencies ?? {})) visit(dep, root);

const entries = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const incompatible = entries.filter((e) => !COMPATIBLE.has(e.license));

const lines = [
  '# Third-party notices',
  '',
  'Kekenik Tree is released under the MIT License (see `LICENSE`). The production build bundles the packages listed below.',
  'This file is generated by `npm run licenses`; do not edit it by hand.',
  '',
  '| Package | Version | License |',
  '|---|---|---|',
  ...entries.map((e) => `| ${e.name} | ${e.version} | ${e.license} |`),
  '',
  '## Assets',
  '',
  '* **Inter** typeface (`@fontsource/inter`, latin 400/500/600 subsets, embedded in the build) - SIL Open Font License 1.1.',
  '* All icons are original inline SVG; all textures, presets and thumbnails are generated procedurally at runtime. `public/favicon.svg` and the icons in `public/` are original artwork released under the project license.',
  '',
  '## License texts',
  '',
  ...entries.flatMap((e) => [`### ${e.name} ${e.version} (${e.license})`, '', e.homepage ? `Source: ${e.homepage.replace(/^git\+/, '')}` : '', '', '```text', e.text || `License: ${e.license}`, '```', '']),
];
writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), `${lines.join('\n')}\n`);
console.warn(`Wrote THIRD_PARTY_NOTICES.md (${entries.length} packages).`);
if (incompatible.length > 0) {
  console.error(`Licenses to review: ${incompatible.map((e) => `${e.name} (${e.license})`).join(', ')}`);
  process.exitCode = 1;
}
