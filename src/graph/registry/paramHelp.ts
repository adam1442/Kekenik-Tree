/** Tooltip for a parameter: explicit text > per-type refinement > id text > prefix rule > label-based sentence. */
export function helpFor(nodeType: string, p: ParamDef): string {
  const own = HELP[`${nodeType}:${p.id}`] ?? HELP[p.id];
  if (own) return own;
  const rule = PREFIX_RULES.find(([re]) => re.test(p.id));
  const where = [p.group, p.subgroup].filter((v): v is string => Boolean(v) && v !== p.group).join(' / ');
  const section = where ? `${p.group} › ${where}` : p.group;
  return `${rule ? `${rule[1]} ` : ''}“${p.label}” in ${section}.`;
}

/** Returns `def` with a tooltip on every parameter (existing tooltips win). List sub-fields are filled as well. */
export function withParamHelp(def: NodeDef): NodeDef {
  const fill = (p: ParamDef): ParamDef => {
    const next: ParamDef = p.tooltip ? p : { ...p, tooltip: helpFor(def.type, p) };
    if (next.kind === 'list') return { ...next, fields: next.fields.map(fill) } as ParamDef;
    return next;
  };
  return { ...def, params: def.params.map(fill) };
}

