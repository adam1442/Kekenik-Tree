import { getApp } from '@/app/context';
import { getLodPreview, type PreviewMode } from '@/export/lod/lodPreview';
import { defaultLodLevels, getLodSettings, MAX_LODS, onLodSettingsChange, setLodSettings } from '@/export/settings';
import { formatCount } from '@/export/stats';
import type { LodLevelSettings } from '@/export/types';
import { h } from '@/ui/components/dom';
import { button, choice, numberInput, slider, toggle } from './dialogs/exportKit';

/**
 * LOD definition table + viewport preview controls. Used by the dockable "LODs" panel and by the Export dialog's LODs tab.
 * Levels are generated by `src/export/lod/*` (generator detail, small-branch removal, foliage thinning + enlargement,
 * triangle budget); the screen-size transitions drive the distance simulation.
 */

const COLUMNS: { title: string; hint: string }[] = [
  { title: 'LOD', hint: 'Level index (0 = highest detail)' },
  { title: 'Detail', hint: 'Generator detail 0-3: radial sides, segments and the per-node LOD curves of the graph' },
  { title: 'Foliage %', hint: 'Share of leaf / frond / mesh pieces kept' },
  { title: 'Keep area', hint: 'Enlarge the remaining foliage so the covered area (silhouette) stays the same' },
  { title: 'Min branch %', hint: 'Branches smaller than this percentage of the plant height are removed' },
  { title: 'Switch at %', hint: 'Screen height percentage at or below which this LOD is used' },
  { title: 'Budget', hint: 'Triangle budget (0 = none): foliage is thinned further to fit' },
  { title: 'Triangles', hint: 'Generated triangle count' },
  { title: '', hint: '' },
];

export function mountLodEditor(host: HTMLElement): () => void {
  const app = getApp();
  const preview = getLodPreview();
  const root = h('div', 'kt-lod');
  host.append(root);
  const table = h('div', 'kt-lod-table');
  const status = h('div', 'kt-lod-status');
  const simReadout = h('span', 'kt-xp-dim');

  const commit = (levels: LodLevelSettings[]): void => setLodSettings({ levels });
  const patch = (i: number, p: Partial<LodLevelSettings>): void => {
    const levels = getLodSettings().levels.map((l, k) => (k === i ? { ...l, ...p } : l));
    commit(levels);
  };

  const renderTable = (): void => {
    const levels = getLodSettings().levels;
    const tris = preview.builtScenes.map((s) => s.stats.triangles);
    const cells: HTMLElement[] = COLUMNS.map((c) => {
      const el = h('div', 'kt-lod-head', c.title);
      el.title = c.hint;
      return el;
    });
    levels.forEach((l, i) => {
      const first = i === 0;
      const remove = button('×', () => commit(levels.filter((_, k) => k !== i)), 'kt-lod-remove');
      remove.title = 'Remove this LOD';
      remove.disabled = levels.length <= 1;
      cells.push(
        h('div', 'kt-lod-name', `LOD ${i}`),
        numberInput(l.engineLod, { min: 0, max: 3, step: 1, decimals: 0, onChange: (v) => patch(i, { engineLod: Math.round(v) }) }),
        numberInput(l.foliageKeep * 100, { min: 2, max: 100, step: 5, decimals: 0, onChange: (v) => patch(i, { foliageKeep: v / 100 }) }),
        toggle(l.keepSilhouette, (v) => patch(i, { keepSilhouette: v })),
        numberInput(l.minBranchSize, { min: 0, max: 50, step: 0.5, decimals: 1, onChange: (v) => patch(i, { minBranchSize: v }) }),
        first
          ? h('div', 'kt-xp-dim', '100')
          : numberInput(l.transition * 100, { min: 0.1, max: 100, step: 1, decimals: 1, onChange: (v) => patch(i, { transition: v / 100 }) }),
        numberInput(l.triangleBudget, { min: 0, max: 50_000_000, step: 1000, decimals: 0, onChange: (v) => patch(i, { triangleBudget: Math.round(v) }) }),
        h('div', 'kt-lod-tris', tris[i] === undefined ? '—' : formatCount(tris[i] as number)),
        remove,
      );
    });
    table.replaceChildren(...cells);
  };

  const renderStatus = (): void => {
    const info = preview.info();
    const parts: string[] = [];
    if (info.building) parts.push('Generating LODs…');
    else if (!info.ready) parts.push('Statistics are out of date: press "Update".');
    if (info.height > 0) parts.push(`Plant height ${info.height.toFixed(1)} m · ${(info.fraction * 100).toFixed(1)} % of the view at ${info.distance.toFixed(1)} m → LOD ${info.activeLod}`);
    status.textContent = parts.join('  ·  ');
    simReadout.textContent = `${preview.simulatedDistance.toFixed(1)} m`;
  };

  const modeItems = (): { value: string; label: string }[] => [
    { value: 'off', label: 'Off (generator LOD)' },
    { value: 'auto', label: 'Auto (by distance)' },
    ...getLodSettings().levels.map((_, i) => ({ value: String(i), label: `LOD ${i}` })),
  ];
  const modeValue = (m: PreviewMode): string => String(m);
  const modeHost = h('div', 'kt-xp-control');
  const renderMode = (): void => {
    modeHost.replaceChildren(
      choice(modeItems(), modeValue(preview.mode), (v) => preview.setMode(v === 'off' || v === 'auto' ? v : Number(v))),
    );
  };

  const simSlider = slider(Math.log10(preview.simulatedDistance) * 100, 0, 230, 1, (v) => {
    preview.setSimulation(preview.simulate, Math.pow(10, v / 100));
  });
  const simToggle = toggle(preview.simulate, (on) => {
    if (on && preview.mode === 'off') preview.setMode('auto');
    preview.setSimulation(on, preview.simulatedDistance);
  });

  const add = button('Add LOD', () => {
    const levels = getLodSettings().levels;
    if (levels.length >= MAX_LODS) return;
    const last = levels[levels.length - 1] as LodLevelSettings;
    commit([...levels, { engineLod: Math.min(3, last.engineLod + 1), foliageKeep: Math.max(0.02, last.foliageKeep * 0.5), keepSilhouette: true, minBranchSize: last.minBranchSize + 3, transition: Math.max(0.005, last.transition * 0.45), triangleBudget: 0 }]);
  });
  const reset = button('Reset', () => commit(defaultLodLevels()));
  const update = button('Update', () => void preview.ensureBuilt());

  root.append(
    h('div', 'kt-lod-bar', h('span', 'kt-xp-label', 'Viewport preview'), modeHost, h('span', 'kt-xp-label', 'Simulate distance'), simToggle, simSlider, simReadout),
    table,
    h('div', 'kt-lod-bar', add, reset, update, h('div', 'kt-em-spacer'), status),
  );
  renderMode();
  renderTable();
  renderStatus();

  const unsubs = [
    preview.onChange(() => {
      renderTable();
      renderStatus();
    }),
    app.store.select((s) => s.stats.cameraDistance, renderStatus),
    onLodSettingsChange(() => {
      renderMode();
      renderTable();
    }),
  ];
  void preview.ensureBuilt();
  return () => {
    unsubs.forEach((u) => u());
    root.remove();
  };
}
